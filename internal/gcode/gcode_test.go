// TestParseIgnoresFreeText is the reason `=` lines are never split on `;`.
//
// PrusaSlicer writes its config block in alphabetical order, so filament_notes,
// notes and printer_notes - three fields the user types into freely - are all
// scanned before layer_height, perimeters and temperature. If a `=` value were
// split into further statements, anyone could put "temperature = 999" in their
// filament notes and the panel would believe it. First-occurrence-wins makes
// that the *winning* value, not a losing one.
func TestParseIgnoresFreeText(t *testing.T) {
	src := strings.Join([]string{
		"; generated by PrusaSlicer 2.9.2 on 2025-01-01 at 00:00:00",
		"G1 X0 Y0",
		"; filament_notes = temperature = 999; layer_height = 9.9; perimeters = 99",
		"; filament_type = PETG",
		"; layer_height = 0.2",
		"; perimeters = 2",
		"; printer_notes = generated by Cura 5.7.1",
		"; temperature = 230",
		"",
	}, "\n")

	got, ok := Parse(strings.NewReader(src), int64(len(src)))
	if !ok {
		t.Fatal("Parse returned false")
	}
	if got.Slicer != "PrusaSlicer" {
		t.Errorf("slicer = %q, want PrusaSlicer; a generator name inside free text was believed", got.Slicer)
	}
	if got.LayerHeightMm == nil || *got.LayerHeightMm != 0.2 {
		t.Errorf("layer height = %v, want 0.2", deref(got.LayerHeightMm))
	}
	if got.WallLoops == nil || *got.WallLoops != 2 {
		t.Errorf("wall loops = %v, want 2", derefInt(got.WallLoops))
	}
	if got.NozzleTempC == nil || *got.NozzleTempC != 230 {
		t.Errorf("nozzle temp = %v, want 230", deref(got.NozzleTempC))
	}
}

// TestParseUnknownSlicer covers the acceptance criterion that a file we cannot
// attribute produces no panel.
//
// The input is a real PrusaSlicer fixture with only its generator line removed,
// so the config block still parses perfectly and sixteen fields are still
// found. Returning true here would put a settings panel on the page with no
// slicer name in its footer, which is the app claiming to understand a file it
// does not.
//
// The second case is why generator detection is anchored to the start of a
// comment rather than searched for anywhere in the line. A user types their own
// text into filament_notes, and it lands in the config block of whatever file
// they slice. If that text can name a slicer, an unrecognised file becomes a
// recognised one and the panel starts reporting a slicer that never touched it.
func TestParseUnknownSlicer(t *testing.T) {
	raw, err := os.ReadFile("testdata/prusaslicer.gcode")
	if err != nil {
		t.Fatal(err)
	}
	var kept []string
	for _, line := range strings.Split(string(raw), "\n") {
		if !strings.Contains(strings.ToLower(line), "generated by") {
			kept = append(kept, line)
		}
	}
	stripped := strings.Join(kept, "\n")

	for _, tc := range []struct {
		name string
		src  string
	}{
		{"no generator line", stripped},
		{
			"generator name only in free text",
			"; filament_notes = generated by PrusaSlicer 9.9\n" + stripped,
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got, ok := Parse(strings.NewReader(tc.src), int64(len(tc.src)))
			if ok {
				t.Errorf("Parse returned true for a file with no recognised generator line; it reported %q %q with %d fields",
					got.Slicer, got.SlicerVersion, got.fields())
			}
			if got.fields() == 0 {
				t.Fatal("fixture no longer parses at all, so this test proves nothing")
			}
		})
	}
}

// TestParseReadsOnlyTwoWindows is the memory constraint, stated as a test.
//
// G-code for a large print runs to hundreds of megabytes, and the upload path
// calls Parse while holding the file open on a request goroutine. This asserts
// the exact reads: two of them, 144 KB in total, at the two ends. A test that
// only checked the parsed output would pass just as happily with an
// io.ReadAll, and the failure would arrive as an out-of-memory in production.
func TestParseReadsOnlyTwoWindows(t *testing.T) {
	raw, err := os.ReadFile("testdata/prusaslicer.gcode")
	if err != nil {
		t.Fatal(err)
	}
	want, _ := Parse(strings.NewReader(string(raw)), int64(len(raw)))

	const size = 600 << 20
	head, tail := splitAtLine(raw, HeadBytes)
	big := &spliced{size: size, segs: []segment{
		{off: 0, data: head},
		{off: size - int64(len(tail)), data: tail},
	}}

	got, ok := Parse(big, size)
	if !ok {
		t.Fatal("Parse returned false")
	}
	if a, b := jsonOf(t, got), jsonOf(t, want); a != b {
		t.Errorf("600 MB file parsed differently from the same bytes read whole:\n%s\nwant:\n%s", a, b)
	}

	if len(big.reads) != 2 {
		t.Fatalf("made %d reads, want 2: %v", len(big.reads), big.reads)
	}
	var total int64
	for _, r := range big.reads {
		total += r.n
	}
	if total != HeadBytes+TailBytes {
		t.Errorf("read %d bytes, want %d", total, HeadBytes+TailBytes)
	}
	if big.reads[0].off != 0 {
		t.Errorf("first read at %d, want 0", big.reads[0].off)
	}
	if big.reads[1].off != size-TailBytes {
		t.Errorf("second read at %d, want %d", big.reads[1].off, size-TailBytes)
	}
}

// TestParseSkipsMiddle states the cost of the two windows out loud: a setting
// that lives neither near the start nor near the end is not read. No slicer
// puts one there today, and this test exists so that if one ever does, the
// person who adds a mid-file key finds out here rather than wondering why the
// field is blank.
func TestParseSkipsMiddle(t *testing.T) {
	const size = 600 << 20
	big := &spliced{size: size, segs: []segment{
		{off: 0, data: []byte("; generated by PrusaSlicer 2.9.2 on 2025-01-01 at 00:00:00\n; layer_height = 0.2\n")},
		{off: size / 2, data: []byte("\n; temperature = 999\n")},
	}}

	got, ok := Parse(big, size)
	if !ok {
		t.Fatal("Parse returned false")
	}
	if got.LayerHeightMm == nil || *got.LayerHeightMm != 0.2 {
		t.Fatalf("layer height = %v, want 0.2", deref(got.LayerHeightMm))
	}
	if got.NozzleTempC != nil {
		t.Errorf("nozzle temp = %v, want absent: a key from the middle of the file was read", *got.NozzleTempC)
	}
}

// TestParseRejectsNonFinite keeps NaN and infinities out of Meta.
//
// json.Marshal refuses to encode either, and the caller marshals during upload,
// so a file containing one would fail the whole upload rather than merely
// producing no settings - the one outcome the product constraint forbids for a
// metadata problem. Both cases here are reachable from a real file: ParseFloat
// accepts the literal word "NaN" for a duration, and two filament totals that
// each fit in a float64 can overflow to +Inf when summed across extruders.
func TestParseRejectsNonFinite(t *testing.T) {
	huge := "17" + strings.Repeat("0", 307) // just under the float64 maximum

	for _, tc := range []struct {
		name string
		line string
	}{
		{"duration NaN", "; estimated printing time (normal mode) = NaN"},
		{"duration Inf", "; estimated printing time (normal mode) = Inf"},
		{"summed overflow", "; filament used [mm] = " + huge + ", " + huge},
		{"layer height NaN", "; layer_height = NaN"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			src := "; generated by PrusaSlicer 2.9.2 on 2025-01-01 at 00:00:00\n" +
				tc.line + "\n; perimeters = 2\n"

			got, ok := Parse(strings.NewReader(src), int64(len(src)))
			if !ok {
				t.Fatal("Parse returned false")
			}
			if got.PrintTimeSeconds != nil {
				t.Errorf("print time = %v, want absent", *got.PrintTimeSeconds)
			}
			if got.FilamentMm != nil {
				t.Errorf("filament length = %v, want absent", *got.FilamentMm)
			}
			if got.LayerHeightMm != nil {
				t.Errorf("layer height = %v, want absent", *got.LayerHeightMm)
			}
			if _, err := json.Marshal(got); err != nil {
				t.Errorf("Meta will not marshal, so the upload would fail: %v", err)
			}
		})
	}
}

