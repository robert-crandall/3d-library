// TestParseDuration covers the two shapes of time a slicer writes. The bare
// number has to be checked first: read as a unit string, Cura's ";TIME:35"
// would be 35 of nothing.
func TestParseDuration(t *testing.T) {
	for _, tc := range []struct {
		in   string
		want int
		ok   bool
	}{
		{"35", 35, true},
		{"57s", 57, true},
		{"12m 5s", 725, true},
		{"1h 47m 18s", 6438, true},
		{"2d 3h 4m 5s", 183845, true},
		{"1h", 3600, true},
		{"", 0, false},
		{"unknown", 0, false},
		{"12x", 0, false},
		{"12m 5", 0, false},

		// Anything that would make int(v) undefined, or make the accumulator
		// wrap. Converting an out-of-range float to int is implementation-
		// dependent in Go, so without the bound these come back as the most
		// negative int64 and the panel renders a print that finished before it
		// started. `NaN` is here because ParseFloat spells it as a number.
		{"1e300", 0, false},
		{"-35", 0, false},
		{"NaN", 0, false},
		{"9999999999999d", 0, false},
		{"4611686018427387904d", 0, false},
		{"1000000h 1000000h 1000000h", 0, false},

		// A sign is not a separator. The loop used to skip every character it
		// did not recognise, which read `-1h` as an hour and made the panel
		// disagree with the file it came from.
		{"-1h", 0, false},
		{"1h -2m", 0, false},
		{"1h x 2m", 0, false},
	} {
		t.Run(tc.in, func(t *testing.T) {
			got, ok := parseDuration(tc.in)
			if ok != tc.ok || (ok && got != tc.want) {
				t.Errorf("parseDuration(%q) = %d, %v; want %d, %v", tc.in, got, ok, tc.want, tc.ok)
			}
		})
	}
}

// A layer count comes out of the same float64 path as every other number, and
// int(1e33) is undefined in Go. This is the whole reason count has a bound: a
// file can legitimately contain a digit run that long, and the result would be
// stored and rendered as -9223372036854775808.
func TestCountRejectsWhatDoesNotFitAnInt(t *testing.T) {
	for _, tc := range []struct {
		value string
		want  string
	}{
		{"3", "3"},
		{"0", "0"},
		{"999999999999999999999999999999999", "absent"},
		{"-1", "absent"},

		// Truncating would have reported 2 walls for a file that says 2.9, and
		// a number nothing in the file supports is worse than no number.
		{"2.9", "absent"},
	} {
		t.Run(tc.value, func(t *testing.T) {
			p := parser{seen: map[string]string{"perimeters": tc.value}}
			got := "absent"
			if n := p.count("perimeters"); n != nil {
				got = strconv.Itoa(*n)
			}
			if got != tc.want {
				t.Errorf("count(%q) = %s, want %s", tc.value, got, tc.want)
			}
		})
	}
}

